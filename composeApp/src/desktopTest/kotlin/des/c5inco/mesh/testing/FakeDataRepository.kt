package des.c5inco.mesh.testing

import data.DataRepository
import data.MeshState
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.updateAndGet
import model.MeshPoint
import model.SavedColor

class FakeDataRepository(
    private val meshPoints: Flow<List<MeshPoint>>,
    // Like the app's presets, the palette is never empty.
    initialColors: List<SavedColor> = List(3) { SavedColor(uid = it + 1L, red = 0, green = 0, blue = 0) },
    private val onSaveMeshPoints: (List<MeshPoint>) -> Unit = {},
    private val initialMeshState: MeshState = MeshState(),
) : DataRepository {
    private val colors = MutableStateFlow(initialColors)

    override fun getAllColors(): Flow<List<SavedColor>> = colors

    override fun getPresetColors(): Flow<List<SavedColor>> = colors

    override fun getCustomColors(): Flow<List<SavedColor>> = colors

    fun setColors(value: List<SavedColor>) {
        colors.value = value
    }

    /** Assigns the next ID, like Room's autogenerated primary key. */
    override suspend fun addColor(color: SavedColor): Long {
        val uid = colors.updateAndGet { existing -> existing + color.copy(uid = (existing.maxOfOrNull { it.uid } ?: 0L) + 1) }
            .last().uid
        return uid
    }

    override fun deleteColor(color: SavedColor) = Unit

    override fun loadMeshState(): MeshState = initialMeshState

    @Volatile
    var savedMeshState: MeshState? = null
        private set

    override fun saveMeshState(state: MeshState) {
        savedMeshState = state
    }

    override fun getMeshPoints(): Flow<List<MeshPoint>> = meshPoints

    override suspend fun saveMeshPoints(points: List<MeshPoint>) = onSaveMeshPoints(points)
}
